"""Mutation methods participate in their caller's existing T1 transaction."""

from typing import Protocol


class LexicalBackend(Protocol):
    def prepare_document(self, memory): ...
    def insert_in_transaction(self, connection, scope, memory, prepared, seq): ...
    def update_in_transaction(self, connection, scope, memory, prepared, seq): ...
    def delete_in_transaction(self, connection, scope, uid): ...
    def search(self, scope, query, **kwargs): ...
    def inspect_stats(self, scope, **kwargs): ...
    def verify_scope(self, scope): ...
    def rebuild_scope(self, scope): ...
    def health(self): ...
    def stats(self): ...
